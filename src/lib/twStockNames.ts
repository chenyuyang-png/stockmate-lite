const seen = new Set<string>();
export const TW_STOCKS: TwStock[] = [];
for (const [code, name, market] of RAW) {
  const sym = `${code}.${market}`;
  if (seen.has(sym)) continue;
  seen.add(sym);
  TW_STOCKS.push({ symbol: sym, code, name, market });
}

const BY_SYMBOL: Record<string, TwStock> = {};
const BY_CODE: Record<string, TwStock> = {};
for (const s of TW_STOCKS) {
  BY_SYMBOL[s.symbol] = s;
  BY_CODE[s.code] = s;
}

export function getTwStockName(symbol: string): string | null {
  return BY_SYMBOL[symbol]?.name ?? null;
}

export function lookupTwSymbol(code: string): string | null {
  return BY_CODE[code]?.symbol ?? null;
}

export function searchTwStocks(query: string, limit = 12): TwStock[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const exact: TwStock[] = [];
  const prefix: TwStock[] = [];
  const contains: TwStock[] = [];
  for (const s of TW_STOCKS) {
    const name = s.name.toLowerCase();
    if (s.code === q || name === q) exact.push(s);
    else if (s.code.startsWith(q) || name.startsWith(q)) prefix.push(s);
    else if (s.code.includes(q) || name.includes(q)) contains.push(s);
  }
  return [...exact, ...prefix, ...contains].slice(0, limit);
}
